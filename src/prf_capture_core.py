def inspect_saved_capture(
    prefix: str | os.PathLike,
    *,
    expected_parameter_set: Optional[str | int] = None,
    expected_fixed_rows: Optional[int] = None,
    expected_random_rows: Optional[int] = None,
) -> Dict[str, Any]:
    """Inspect and validate split arrays written by the capture helpers.

    v8 compatibility semantics
    --------------------------
    ``expected_*_rows`` is treated as the MINIMUM number of rows required,
    rather than requiring an exact physical file size.  This allows an older
    10k dataset to satisfy a newer CPA request that analyzes only the first 5k.

    If ``expected_*_rows == 0`` and that split is intentionally absent
    (for example fixed=0 in random-only CPA capture), a virtual empty split is
    returned so legacy notebook verification code can safely access
    ``result["fixed"]["traces_shape"]`` without a NoneType error.

    Existing physical files are never modified by this function.
    """
    prefix_n = windows_to_wsl_path(prefix)
    suffixes = [
        "_traces_fixed.npy",
        "_traces_random.npy",
        "_addrs_fixed.npy",
        "_addrs_random.npy",
        "_params_fixed.npy",
        "_params_random.npy",
        "_meta_columns.npy",
        "_capture_config.json",
    ]
    for suffix in suffixes:
        if prefix_n.endswith(suffix):
            prefix_n = prefix_n[:-len(suffix)]
            break
    if prefix_n.endswith(".npz"):
        prefix_n = prefix_n[:-4]

    result: Dict[str, Any] = {"prefix": prefix_n}

    config_path = prefix_n + "_capture_config.json"
    if not os.path.exists(config_path):
        raise FileNotFoundError(config_path)

    with open(config_path, "r", encoding="utf-8") as file:
        config = json.load(file)
    result["config"] = config

    if expected_parameter_set is not None:
        expected = normalize_param_set(expected_parameter_set)
        actual = normalize_param_set(config["parameter_set"])
        if actual != expected:
            raise ValueError(
                f"parameter-set mismatch: saved={actual}, expected={expected}"
            )

    for split, expected_rows in (
        ("fixed", expected_fixed_rows),
        ("random", expected_random_rows),
    ):
        trace_path = prefix_n + f"_traces_{split}.npy"
        addr_path = prefix_n + f"_addrs_{split}.npy"
        param_path = prefix_n + f"_params_{split}.npy"

        exists = [
            os.path.exists(trace_path),
            os.path.exists(addr_path),
            os.path.exists(param_path),
        ]

        requested_rows = (
            None if expected_rows is None else int(expected_rows)
        )
        if requested_rows is not None and requested_rows < 0:
            raise ValueError(
                f"{split} expected row count must be non-negative"
            )

        # Random-only CPA mode: fixed split is intentionally not created.
        # Return an empty compatibility record instead of None when caller
        # explicitly requested zero rows.
        if not any(exists):
            if requested_rows == 0:
                result[split] = {
                    "traces_shape": (0, 0),
                    "addrs_shape": (0, ADRS_FULL_BYTES),
                    "params_shape": (0, len(META_COLUMNS)),
                    "available_rows": 0,
                    "requested_rows": 0,
                    "analysis_rows": 0,
                    "virtual_empty": True,
                }
            else:
                result[split] = None
            continue

        if not all(exists):
            raise FileNotFoundError(
                f"incomplete {split} split for prefix={prefix_n}"
            )

        traces = np.load(trace_path, mmap_mode="r")
        addrs = np.load(addr_path, mmap_mode="r")
        params = np.load(param_path, mmap_mode="r")

        if (
            traces.shape[0] != addrs.shape[0]
            or traces.shape[0] != params.shape[0]
        ):
            raise ValueError(
                f"{split} row mismatch: traces={traces.shape}, "
                f"addrs={addrs.shape}, params={params.shape}"
            )

        if addrs.ndim != 2 or addrs.shape[1] != ADRS_FULL_BYTES:
            raise ValueError(
                f"{split} address width mismatch: {addrs.shape}"
            )

        available_rows = int(traces.shape[0])

        # Compatibility rule: an existing larger dataset is valid.
        # Example: available=10000, requested=5000 -> accepted.
        if (
            requested_rows is not None
            and available_rows < requested_rows
        ):
            raise ValueError(
                f"{split} row count={available_rows}, "
                f"requires at least={requested_rows}"
            )

        result[split] = {
            "traces_shape": tuple(int(x) for x in traces.shape),
            "addrs_shape": tuple(int(x) for x in addrs.shape),
            "params_shape": tuple(int(x) for x in params.shape),
            "available_rows": available_rows,
            "requested_rows": requested_rows,
            "analysis_rows": (
                available_rows
                if requested_rows is None
                else requested_rows
            ),
            "virtual_empty": False,
        }

    return result


