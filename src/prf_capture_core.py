def calibrate_and_set_samples(
    scope,
    target,
    *,
    calibration_kind: str = "wots",
    mode: int | str = "sha2",
    pk_seed: Optional[bytes] = None,
    sk_seed: Optional[bytes] = None,
    sk_prf: Optional[bytes] = None,
    timeout: int = 250,
    auto_calibrate: bool = True,
    margin: int = 50,
    max_samples: int = DEFAULT_MAX_SAMPLES,
    manual_samples: int = -1,
    verify_addr: bool = True,
) -> Dict[str, Any]:
    mode_i = normalize_mode(mode)
    pk_seed, sk_seed, sk_prf = _resolve_seeds(pk_seed, sk_seed, sk_prf)
    configure_static(target, mode=mode_i, pk_seed=pk_seed, sk_seed=sk_seed, sk_prf=sk_prf, timeout=timeout)

    case = make_calibration_case(calibration_kind, mode=mode_i)
    send_addr(target, case.addr, timeout=timeout, verify=verify_addr)
    result, wave = capture_trace(scope, target, timeout=timeout)
    expected = reference_digest(mode_i, pk_seed, sk_seed, case.addr)
    if result != expected:
        raise RuntimeError(f"calibration digest mismatch\n got={result.hex()}\n exp={expected.hex()}")

    actual_trigger_length = int(getattr(scope.adc, "trig_count", 0))
    if auto_calibrate and actual_trigger_length > 0:
        calibrated_samples = min(actual_trigger_length + int(margin), int(max_samples))
        scope.adc.samples = int(calibrated_samples)
        selected_samples = int(scope.adc.samples)
    elif int(manual_samples) > 0:
        scope.adc.samples = min(int(manual_samples), int(max_samples))
        selected_samples = int(scope.adc.samples)
    else:
        selected_samples = int(scope.adc.samples)

    return {
        "case": case,
        "result": result,
        "expected": expected,
        "match": result == expected,
        "wave": np.asarray(wave, dtype=np.float32),
        "wave_len": int(len(wave)),
        "trig_count": actual_trigger_length,
        "scope_samples": selected_samples,
        "mode": mode_i,
        "mode_name": mode_name(mode_i),
        "kind": str(calibration_kind).lower(),
    }

