def _public_demo_seed_hex(role: str, width: int) -> str:
    label = f"SLH-DSA-CAPTURE-PUBLIC-DEMO/{role}/{int(width)}".encode("ascii")
    data = hashlib.shake_256(label).digest(int(width))
    return " ".join(f"{b:02X}" for b in data)


