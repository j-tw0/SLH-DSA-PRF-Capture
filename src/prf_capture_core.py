def capture_multi_seed_fixed_random_experiment(
    scope,
    target,
    output_dir: str | os.PathLike,
    *,
    platform: str,
    seeds: Sequence[bytes],
    kind: str,
    tvla_fixed_traces: Optional[int] = None,
    tvla_random_traces: Optional[int] = None,
    cpa_random_traces: Optional[int] = None,
    n_fixed: Optional[int] = None,
    n_random: Optional[int] = None,
    mode: int | str = "sha2",
    capture_rng_seed: int = 1234,
    pk_seed: Optional[bytes] = None,
    sk_prf: Optional[bytes] = None,
    timeout: int = 250,
    shuffle_sequence: bool = True,
    verify_addr_each_time: bool = False,
    verify_result: bool = True,
    verify_first_n: int = 5,
    flush_every: int = 1000,
    resume: bool = True,
    compatible_resume: bool = True,
    fixed_seed_policy: str = "auto_os_first",
    fixed_seed_index: int = 0,
    ignore_existing_fixed_nonprimary: bool = True,
) -> Dict[str, Any]:
    """Run WOTS/FORS capture with separate TVLA and CPA trace-count settings."""
    kind_l = str(kind).strip().lower()

    aliases = {
        "wots": "wots",
        "wots+": "wots",
        "fors": "fors",
        "both": "both",
        "all": "both",
        "wots+fors": "both",
        "wots_fors": "both",
    }
    if kind_l not in aliases:
        raise ValueError("kind must be 'wots', 'fors', or 'both'")

    explicit_counts = (
        tvla_fixed_traces is not None
        or tvla_random_traces is not None
        or cpa_random_traces is not None
    )
    if explicit_counts:
        if (
            tvla_fixed_traces is None
            or tvla_random_traces is None
            or cpa_random_traces is None
        ):
            raise ValueError(
                "tvla_fixed_traces, tvla_random_traces, and "
                "cpa_random_traces must be specified together"
            )
        summary_tvla_fixed = int(tvla_fixed_traces)
        summary_tvla_random = int(tvla_random_traces)
        summary_cpa_random = int(cpa_random_traces)
    else:
        if n_fixed is None or n_random is None:
            raise ValueError(
                "Specify explicit TVLA/CPA counts or legacy n_fixed/n_random"
            )
        summary_tvla_fixed = int(n_fixed)
        summary_tvla_random = int(n_random)
        summary_cpa_random = int(n_random)

    selected = aliases[kind_l]
    kinds = ("wots", "fors") if selected == "both" else (selected,)

    results: Dict[str, Any] = {
        "format": "slh-dsa-multiseed-tvla-cpa-experiment-v10",
        "parameter_set": ACTIVE_PARAM_SET,
        "profile": PARAMS.profile_name,
        "mode": mode_name(mode),
        "requested_kind": selected,
        "num_secret_seeds": len(seeds),
        "tvla_fixed_traces": summary_tvla_fixed,
        "tvla_random_traces": summary_tvla_random,
        "cpa_random_traces": summary_cpa_random,
        "capture_rng_seed": int(capture_rng_seed),
        "shuffle_sequence": bool(shuffle_sequence),
        "build": get_capture_build_metadata(),
        "compatible_resume": bool(compatible_resume),
        "fixed_seed_policy": str(fixed_seed_policy),
        "fixed_seed_index": int(fixed_seed_index),
        "ignore_existing_fixed_nonprimary": bool(
            ignore_existing_fixed_nonprimary
        ),
        "datasets": {},
    }

    output_root = windows_to_wsl_path(output_dir)
    os.makedirs(output_root, exist_ok=True)

    print("===== TVLA / CPA multi-seed experiment =====")
    print("requested kind :", selected)
    print("execution order:", " -> ".join(kinds))
    print("secret seeds   :", len(seeds))
    print("TVLA F / R     :", summary_tvla_fixed, "/", summary_tvla_random)
    print("CPA random     :", summary_cpa_random)
    print("TVLA policy    :", fixed_seed_policy)
    print("TVLA seed id   :", int(fixed_seed_index))
    print("capture RNG    :", int(capture_rng_seed))

    for current_kind in kinds:
        print()
        print("=" * 78)
        print(
            f"START {current_kind.upper()} "
            f"({len(seeds)} secret seeds)"
        )
        print("=" * 78)

        current_result = capture_multi_seed_fixed_random_sets(
            scope,
            target,
            output_root,
            platform=platform,
            seeds=seeds,
            kind=current_kind,
            tvla_fixed_traces=tvla_fixed_traces,
            tvla_random_traces=tvla_random_traces,
            cpa_random_traces=cpa_random_traces,
            n_fixed=n_fixed,
            n_random=n_random,
            mode=mode,
            capture_rng_seed=capture_rng_seed,
            pk_seed=pk_seed,
            sk_prf=sk_prf,
            timeout=timeout,
            shuffle_sequence=shuffle_sequence,
            verify_addr_each_time=verify_addr_each_time,
            verify_result=verify_result,
            verify_first_n=verify_first_n,
            flush_every=flush_every,
            resume=resume,
            compatible_resume=compatible_resume,
            fixed_seed_policy=fixed_seed_policy,
            fixed_seed_index=fixed_seed_index,
            ignore_existing_fixed_nonprimary=(
                ignore_existing_fixed_nonprimary
            ),
        )
        results["datasets"][current_kind] = current_result

        print()
        print(
            f"DONE {current_kind.upper()}:",
            len(current_result["completed"]),
            "/",
            len(seeds),
            "secret seeds",
        )

    combined_manifest_path = os.path.join(
        output_root,
        "multi_seed_fixed_random_both_summary.json",
    )

    compact = dict(results)
    compact["datasets"] = {
        name: {
            "kind": result["kind"],
            "num_secret_seeds": result["num_secret_seeds"],
            "tvla_fixed_traces": result["tvla_fixed_traces"],
            "tvla_random_traces": result["tvla_random_traces"],
            "cpa_random_traces": result["cpa_random_traces"],
            "fixed_seed_policy": result["fixed_seed_policy"],
            "fixed_seed_index": result["fixed_seed_index"],
            "compiler_optimization_detected": result[
                "compiler_optimization_detected"
            ],
            "completed_seed_ids": [
                int(row["seed_id"])
                for row in result["completed"]
            ],
            "progress_manifest": _multi_seed_fixed_random_progress_path(
                output_root,
                name,
            ),
        }
        for name, result in results["datasets"].items()
    }

    with open(
        combined_manifest_path,
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(compact, file, ensure_ascii=False, indent=2)

    results["combined_manifest"] = combined_manifest_path
    print()
    print("Combined summary:", combined_manifest_path)
    return results


def verify_multi_seed_capture_result(
    multi_seed_result: Dict[str, Any],
    *,
    expected_parameter_set: Optional[str | int] = None,
) -> List[Dict[str, Any]]:
    """Compact verification helper for mixed TVLA/CPA per-seed datasets."""
    rows: List[Dict[str, Any]] = []

    for kind_name, kind_result in multi_seed_result["datasets"].items():
        for row in kind_result["completed"]:
            prefix = row["capture_prefix"]
            inspected = inspect_saved_capture(
                prefix,
                expected_parameter_set=expected_parameter_set,
                expected_fixed_rows=None,
                expected_random_rows=None,
            )

            fixed_info = inspected.get("fixed")
            random_info = inspected.get("random")
            fixed_rows = (
                0 if fixed_info is None
                else int(fixed_info["traces_shape"][0])
            )
            random_rows = (
                0 if random_info is None
                else int(random_info["traces_shape"][0])
            )

            required_fixed = int(
                row.get("required_stored_fixed_rows", 0)
            )
            required_random = int(
                row.get(
                    "required_stored_random_rows",
                    row.get("cpa_random_rows", 0),
                )
            )

            if fixed_rows < required_fixed:
                raise RuntimeError(
                    f"{kind_name} seed {row['seed_id']}: "
                    f"fixed rows {fixed_rows} < required {required_fixed}"
                )
            if random_rows < required_random:
                raise RuntimeError(
                    f"{kind_name} seed {row['seed_id']}: "
                    f"random rows {random_rows} < required {required_random}"
                )

            rows.append({
                "kind": kind_name,
                "seed_id": int(row["seed_id"]),
                "status": row.get("status"),
                "tvla_enabled": bool(row.get("tvla_enabled", False)),
                "stored_fixed_rows": fixed_rows,
                "stored_random_rows": random_rows,
                "tvla_fixed_rows": int(row.get("tvla_fixed_rows", 0)),
                "tvla_random_rows": int(row.get("tvla_random_rows", 0)),
                "cpa_random_rows": int(row.get("cpa_random_rows", 0)),
                "capture_prefix": prefix,
            })

    return rows


def verify_cpa_random_address_consistency(
    multi_seed_result: Dict[str, Any],
    *,
    cpa_random_traces: Optional[int] = None,
) -> Dict[str, bool]:
    """Check that the CPA random-address prefix is identical across seeds."""
    count = (
        int(multi_seed_result["cpa_random_traces"])
        if cpa_random_traces is None
        else int(cpa_random_traces)
    )
    results: Dict[str, bool] = {}

    for kind_name, kind_result in multi_seed_result["datasets"].items():
        reference = None
        same = True

        for row in kind_result["completed"]:
            addrs = np.load(
                row["capture_prefix"] + "_addrs_random.npy",
                mmap_mode="r",
            )
            if addrs.shape[0] < count:
                raise RuntimeError(
                    f"{kind_name} seed {row['seed_id']}: "
                    f"only {addrs.shape[0]} random addresses, need {count}"
                )

            current = np.asarray(addrs[:count])
            if reference is None:
                reference = current.copy()
            elif not np.array_equal(reference, current):
                same = False
                break

        results[kind_name] = same

    return results

