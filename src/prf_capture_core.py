def capture_multi_seed_cpa_sets(
    scope,
    target,
    output_dir: str | os.PathLike,
    *,
    platform: str,
    seeds: Sequence[bytes],
    kind: str,
    n_traces: int,
    mode: int | str = "sha2",
    address_rng_seed: int = 1234,
    mixed_wots_ratio: float = 0.5,
    signature_style: str = "treehash_full",
    pk_seed: Optional[bytes] = None,
    sk_prf: Optional[bytes] = None,
    timeout: int = 250,
    verify_addr_each_time: bool = False,
    verify_result: bool = True,
    verify_first_n: int = 5,
    flush_every: int = 1000,
    resume: bool = True,
    compatible_resume: bool = True,
) -> Dict[str, Any]:
    """Capture one independent CPA trace set for each supplied SK.seed.

    Each seed is kept fixed for all n_traces in its dataset.  The same
    address_rng_seed is restarted for every seed, so address row i is the same
    across secret seeds and, when the same configuration is reused, across
    compiler optimization levels.

    kind:
        "wots", "fors", "mixed", or "signature_exact"

    Output:
        <output_dir>/multi_seed_<kind>/
            seed_000/
            seed_001/
            ...
        plus a resumable multi-seed capture manifest.
    """
    kind_l = str(kind).strip().lower()
    if kind_l not in ("wots", "fors", "mixed", "signature_exact"):
        raise ValueError(
            "kind must be 'wots', 'fors', 'mixed', or 'signature_exact'"
        )

    total_traces = int(n_traces)
    if total_traces <= 0:
        raise ValueError("n_traces must be positive")

    seed_list = [bytes(seed) for seed in seeds]
    if not seed_list:
        raise ValueError("seeds is empty")

    for seed in seed_list:
        _require_len("SK.seed", seed, SLH_N)

    root = os.path.join(
        windows_to_wsl_path(output_dir),
        f"multi_seed_{kind_l}",
    )
    os.makedirs(root, exist_ok=True)

    progress_path = _multi_seed_capture_progress_path(
        output_dir,
        kind_l,
    )

    base_build_metadata = get_capture_build_metadata()
    base_manifest = {
        "format": "slh-dsa-multi-seed-capture-v1",
        "parameter_set": ACTIVE_PARAM_SET,
        "profile": PARAMS.profile_name,
        "mode": mode_name(mode),
        "kind": kind_l,
        "n": SLH_N,
        "num_secret_seeds": len(seed_list),
        "traces_per_seed": total_traces,
        "address_rng_seed": int(address_rng_seed),
        "mixed_wots_ratio": float(mixed_wots_ratio),
        "signature_style": str(signature_style),
        "build": dict(base_build_metadata),
        "completed": [],
    }

    completed_by_id: Dict[int, Dict[str, Any]] = {}

    if bool(resume) and os.path.exists(progress_path):
        with open(progress_path, "r", encoding="utf-8") as file:
            old = json.load(file)

        comparable_fields = (
            "parameter_set",
            "mode",
            "kind",
            "n",
            "num_secret_seeds",
            "traces_per_seed",
            "address_rng_seed",
        )
        for field in comparable_fields:
            if old.get(field) != base_manifest.get(field):
                raise ValueError(
                    f"existing multi-seed manifest mismatch for {field}: "
                    f"saved={old.get(field)!r}, requested={base_manifest.get(field)!r}"
                )

        for row in old.get("completed", []):
            completed_by_id[int(row["seed_id"])] = row

        base_manifest["completed"] = list(
            completed_by_id.values()
        )

    def write_progress() -> None:
        with open(progress_path, "w", encoding="utf-8") as file:
            json.dump(
                base_manifest,
                file,
                ensure_ascii=False,
                indent=2,
            )

    write_progress()

    pk = PUB_SEED if pk_seed is None else bytes(pk_seed)
    prf = SK_PRF if sk_prf is None else bytes(sk_prf)
    _require_len("pk_seed", pk, SLH_N)
    _require_len("sk_prf", prf, SLH_N)

    print("===== Multi-seed CPA capture =====")
    print("parameter set   :", ACTIVE_PARAM_SET)
    print("mode            :", mode_name(mode))
    print("kind            :", kind_l)
    print("secret seeds    :", len(seed_list))
    print("traces / seed   :", total_traces)
    print("address RNG seed:", int(address_rng_seed))
    print("output root     :", root)
    print("resume          :", bool(resume))

    try:
        for seed_id, sk_seed_value in enumerate(seed_list):
            seed_hash = hashlib.sha256(
                sk_seed_value
            ).hexdigest()

            if seed_id in completed_by_id:
                saved_hash = completed_by_id[seed_id].get(
                    "sk_seed_sha256"
                )
                if saved_hash != seed_hash:
                    raise ValueError(
                        f"seed {seed_id} hash differs from the "
                        "existing completed capture"
                    )
                print(
                    f"[seed {seed_id:03d}] already completed -> skip"
                )
                continue

            seed_dir = os.path.join(
                root,
                f"seed_{seed_id:03d}",
            )
            os.makedirs(seed_dir, exist_ok=True)

            seed_metadata = dict(base_build_metadata)
            seed_metadata.update({
                "seed_id": int(seed_id),
                "sk_seed_sha256": seed_hash,
                "traces_per_seed": total_traces,
                "address_rng_seed": int(address_rng_seed),
                "multi_seed_kind": kind_l,
            })
            set_capture_build_metadata(seed_metadata)

            # Explicitly set all static values at the beginning of every
            # independent secret-key experiment.
            configure_static(
                target,
                mode=mode,
                pk_seed=pk,
                sk_seed=sk_seed_value,
                sk_prf=prf,
                timeout=timeout,
            )

            print()
            print("-" * 72)
            print(
                f"Seed {seed_id + 1}/{len(seed_list)} "
                f"(id={seed_id:03d})"
            )
            print("SK.seed SHA-256:", seed_hash)
            print("-" * 72)

            extra_info: Dict[str, Any] = {}

            if kind_l in ("wots", "fors", "mixed"):
                prefix = capture_random_count(
                    scope,
                    target,
                    seed_dir,
                    platform=platform,
                    kind=kind_l,
                    n_traces=total_traces,
                    mode=mode,
                    mixed_wots_ratio=float(
                        mixed_wots_ratio
                    ),
                    pk_seed=pk,
                    sk_seed=sk_seed_value,
                    sk_prf=prf,
                    timeout=timeout,
                    rng_seed=int(address_rng_seed),
                    verify_addr_each_time=verify_addr_each_time,
                    verify_result=verify_result,
                    verify_first_n=verify_first_n,
                    flush_every=flush_every,
                )
            else:
                prefix, infos = capture_signature_exact_count(
                    scope,
                    target,
                    seed_dir,
                    platform=platform,
                    n_traces=total_traces,
                    style=signature_style,
                    address_seed=int(address_rng_seed),
                    mode=mode,
                    pk_seed=pk,
                    sk_seed=sk_seed_value,
                    sk_prf=prf,
                    timeout=timeout,
                    verify_addr_each_time=verify_addr_each_time,
                    verify_result=verify_result,
                    verify_first_n=verify_first_n,
                    flush_every=flush_every,
                )
                extra_info["signature_infos"] = infos

            row = {
                "seed_id": int(seed_id),
                "sk_seed_sha256": seed_hash,
                "capture_prefix": str(prefix),
                "seed_output_dir": str(seed_dir),
                "status": "completed",
            }
            row.update(extra_info)

            completed_by_id[seed_id] = row
            base_manifest["completed"] = [
                completed_by_id[key]
                for key in sorted(completed_by_id)
            ]
            write_progress()

    finally:
        # Restore the build-level metadata after per-seed metadata injection.
        set_capture_build_metadata(base_build_metadata)

    print()
    print("multi-seed capture manifest:", progress_path)
    print(
        "completed:",
        len(base_manifest["completed"]),
        "/",
        len(seed_list),
    )

    return base_manifest


