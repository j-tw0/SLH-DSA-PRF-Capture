def capture_random_count_streaming(
    scope,
    target,
    prefix: str,
    *,
    kind: str,
    n_traces: int,
    mode: int | str = "sha2",
    mixed_wots_ratio: float = 0.5,
    pk_seed: Optional[bytes] = None,
    sk_seed: Optional[bytes] = None,
    sk_prf: Optional[bytes] = None,
    timeout: int = 250,
    rng_seed: int = 1234,
    verify_addr_each_time: bool = False,
    verify_result: bool = True,
    verify_first_n: int = 5,
    flush_every: int = 1000,
) -> str:
    """Capture exactly ``n_traces`` random WOTS/FORS/mixed PRF traces.

    kind:
        "wots"  -> every address is WOTS PRF.
        "fors"  -> every address is FORS PRF.
        "mixed" -> WOTS/FORS are selected per trace using mixed_wots_ratio.

    The active f/s parameter set controls all address ranges.
    """
    prefix = windows_to_wsl_path(prefix)
    os.makedirs(os.path.dirname(prefix) or ".", exist_ok=True)

    total = int(n_traces)
    if total <= 0:
        raise ValueError("n_traces must be positive")

    kind_l = str(kind).strip().lower()
    if kind_l not in ("wots", "fors", "mixed"):
        raise ValueError("kind must be 'wots', 'fors', or 'mixed'")

    ratio = float(mixed_wots_ratio)
    if not 0.0 <= ratio <= 1.0:
        raise ValueError("mixed_wots_ratio must be in [0, 1]")

    mode_i = normalize_mode(mode)
    mode_l = mode_name(mode_i)
    pk_seed, sk_seed, sk_prf = _resolve_seeds(
        pk_seed,
        sk_seed,
        sk_prf,
    )

    configure_static(
        target,
        mode=mode_i,
        pk_seed=pk_seed,
        sk_seed=sk_seed,
        sk_prf=sk_prf,
        timeout=timeout,
    )

    rng = random.Random(int(rng_seed))
    _save_meta_columns(prefix)

    traces_mm = None
    _, addrs_mm, params_mm = _init_split_arrays(
        prefix,
        "random",
        total,
    )
    trace_len = None
    wots_count = 0
    fors_count = 0

    print("parameter set:", ACTIVE_PARAM_SET)
    print("profile      :", PARAMS.profile_name)
    print("mode         :", mode_l)
    print("kind         :", kind_l)
    print("requested    :", total)
    if kind_l == "mixed":
        print("WOTS ratio   :", ratio)
    print("scope.adc.samples:", int(scope.adc.samples))
    print(
        "verify outputs:",
        "all"
        if int(verify_first_n) < 0
        else f"first {int(verify_first_n)}",
    )

    for index in tqdm(
        range(total),
        desc=f"{ACTIVE_PARAM_SET}/{mode_l}/{kind_l}",
    ):
        if kind_l == "mixed":
            selected_kind = (
                "wots"
                if rng.random() < ratio
                else "fors"
            )
        else:
            selected_kind = kind_l

        case = make_case_for_kind(
            selected_kind,
            False,
            rng,
            mode=mode_i,
        )
        if selected_kind == "wots":
            wots_count += 1
        else:
            fors_count += 1

        send_addr(
            target,
            case.addr,
            timeout=timeout,
            verify=verify_addr_each_time,
        )
        result, wave = capture_trace(
            scope,
            target,
            timeout=timeout,
        )

        if verify_result and (
            int(verify_first_n) < 0
            or index < int(verify_first_n)
        ):
            _verify_digest_or_raise(
                mode_i,
                pk_seed,
                sk_seed,
                case,
                result,
                index=index,
            )

        wave = np.asarray(
            wave,
            dtype=np.float32,
        )

        if trace_len is None:
            trace_len = _trace_len_from_wave(
                scope,
                wave,
            )
            print("captured_len:", int(wave.shape[0]))
            print(
                "requested_len(scope.adc.samples):",
                int(scope.adc.samples),
            )
            print("save trace_len:", int(trace_len))

            traces_mm = open_memmap(
                prefix + "_traces_random.npy",
                mode="w+",
                dtype=np.float32,
                shape=(total, trace_len),
            )

        if wave.shape[0] < trace_len:
            raise RuntimeError(
                f"trace too short: got {wave.shape[0]}, "
                f"expected at least {trace_len}"
            )

        traces_mm[index, :] = wave[:trace_len]
        addrs_mm[index, :] = np.frombuffer(
            case.addr,
            dtype=np.uint8,
        )
        params_mm[index, :] = np.asarray(
            case.meta_row(
                is_fixed=0,
                mode=mode_i,
            ),
            dtype=np.uint64,
        )

        if (index + 1) % int(flush_every) == 0:
            _flush_many(
                traces_mm,
                addrs_mm,
                params_mm,
            )

    _flush_many(
        traces_mm,
        addrs_mm,
        params_mm,
    )

    print("saved prefix :", prefix)
    print("captured     :", total)
    print("WOTS count   :", wots_count)
    print("FORS count   :", fors_count)
    return prefix


