# ---------------------------------------------------------------------------
def generate_reproducible_secret_seeds(
    num_seeds: int,
    master_seed: int,
    *,
    n: Optional[int] = None,
) -> List[bytes]:
    """Generate a reproducible set of distinct SK.seed values.

    A deterministic PRNG is deliberately used here so the exact same secret
    seed set can be replayed for -O0/-O1/-O2/-O3/-Os builds. These are
    experimental ground-truth keys, not production key-generation material.
    """
    count = int(num_seeds)
    if count <= 0:
        raise ValueError("num_seeds must be positive")

    width = SLH_N if n is None else int(n)
    if width <= 0:
        raise ValueError("n must be positive")

    rng = random.Random(int(master_seed))
    seeds: List[bytes] = []
    seen = set()

    while len(seeds) < count:
        candidate = bytes(
            rng.getrandbits(8)
            for _ in range(width)
        )
        if candidate in seen:
            continue
        seen.add(candidate)
        seeds.append(candidate)

    return seeds


def load_or_create_secret_seed_manifest(
    manifest_path: str | os.PathLike,
    *,
    num_seeds: int,
    master_seed: int,
    parameter_set: Optional[str | int] = None,
    overwrite: bool = False,
) -> Tuple[List[bytes], Dict[str, Any]]:
    """Load/create a shared deterministic SK.seed pool.

    v12 allows different experiments to request different numbers of seeds
    while reusing the same shared manifest and deterministic ordering.

    Behavior:
      * saved_count > requested_count:
          Return only seed_000 .. seed_(requested_count-1).
          Keep the larger manifest file unchanged.
      * saved_count == requested_count:
          Return the full saved set.
      * saved_count < requested_count:
          Deterministically extend the pool to the requested size using the
          same master seed, after verifying that the old pool is the exact
          prefix of the regenerated set.

    Parameter set, n, and master_seed must still match.
    """
    path = windows_to_wsl_path(manifest_path)
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)

    param_name = (
        ACTIVE_PARAM_SET
        if parameter_set is None
        else normalize_param_set(parameter_set)
    )
    params = get_parameter_set(param_name)

    requested_count = int(num_seeds)
    requested_master = int(master_seed)

    if requested_count <= 0:
        raise ValueError("num_seeds must be positive")

    if os.path.exists(path) and not bool(overwrite):
        with open(path, "r", encoding="utf-8") as file:
            manifest = json.load(file)

        saved_param = normalize_param_set(
            manifest["parameter_set"]
        )
        saved_n = int(manifest["n"])
        saved_count = int(manifest["num_seeds"])
        saved_master = int(manifest["master_seed"])

        if saved_param != param_name:
            raise ValueError(
                f"seed manifest parameter mismatch: "
                f"saved={saved_param}, requested={param_name}"
            )
        if saved_n != params.n:
            raise ValueError(
                f"seed manifest n mismatch: "
                f"saved={saved_n}, expected={params.n}"
            )
        if saved_master != requested_master:
            raise ValueError(
                f"seed manifest master_seed mismatch: "
                f"saved={saved_master}, requested={requested_master}"
            )

        rows = manifest.get("seeds", [])
        if len(rows) != saved_count:
            raise ValueError(
                "seed manifest row count does not match saved num_seeds"
            )

        saved_seeds = [
            bytes.fromhex(row["sk_seed_hex"])
            for row in rows
        ]
        for seed in saved_seeds:
            _require_len(
                "SK.seed from manifest",
                seed,
                params.n,
            )

        # --------------------------------------------------------------
        # Existing pool is large enough: use only the requested prefix.
        # Do not shrink or rewrite the manifest.
        # --------------------------------------------------------------
        if saved_count >= requested_count:
            selected_seeds = saved_seeds[:requested_count]

            runtime_manifest = dict(manifest)
            runtime_manifest["stored_num_seeds"] = saved_count
            runtime_manifest["requested_num_seeds"] = requested_count
            runtime_manifest["selected_seed_ids"] = list(
                range(requested_count)
            )
            runtime_manifest["selection_mode"] = (
                "exact_existing_pool"
                if saved_count == requested_count
                else "prefix_from_existing_pool"
            )

            if saved_count > requested_count:
                print(
                    "Shared SK.seed pool:",
                    f"stored={saved_count}, requested={requested_count}",
                )
                print(
                    f"Using seed_000 .. "
                    f"seed_{requested_count - 1:03d}; "
                    f"the remaining {saved_count - requested_count} "
                    "stored seeds are preserved."
                )

            return selected_seeds, runtime_manifest

        # --------------------------------------------------------------
        # Requested pool is larger: regenerate deterministically, verify
        # the existing saved pool is its exact prefix, then extend file.
        # --------------------------------------------------------------
        expanded_seeds = generate_reproducible_secret_seeds(
            requested_count,
            requested_master,
            n=params.n,
        )

        if expanded_seeds[:saved_count] != saved_seeds:
            raise ValueError(
                "existing seed manifest is not the deterministic prefix "
                "generated by the saved master_seed; refusing to extend"
            )

        manifest = {
            "format": "slh-dsa-shared-secret-seeds-v1",
            "parameter_set": param_name,
            "security_bits": params.security_bits,
            "n": params.n,
            "num_seeds": requested_count,
            "master_seed": requested_master,
            "purpose": (
                "Paired side-channel acquisition across compiler "
                "optimization levels"
            ),
            "seeds": [
                {
                    "seed_id": index,
                    "sk_seed_hex": seed.hex(),
                    "sha256": hashlib.sha256(seed).hexdigest(),
                }
                for index, seed in enumerate(expanded_seeds)
            ],
        }

        with open(path, "w", encoding="utf-8") as file:
            json.dump(
                manifest,
                file,
                ensure_ascii=False,
                indent=2,
            )

        runtime_manifest = dict(manifest)
        runtime_manifest["stored_num_seeds"] = requested_count
        runtime_manifest["requested_num_seeds"] = requested_count
        runtime_manifest["selected_seed_ids"] = list(
            range(requested_count)
        )
        runtime_manifest["selection_mode"] = "extended_existing_pool"

        print(
            "Extended shared SK.seed pool:",
            f"{saved_count} -> {requested_count}",
        )

        return expanded_seeds, runtime_manifest

    # ------------------------------------------------------------------
    # No existing manifest, or overwrite=True.
    # ------------------------------------------------------------------
    seeds = generate_reproducible_secret_seeds(
        requested_count,
        requested_master,
        n=params.n,
    )

    manifest = {
        "format": "slh-dsa-shared-secret-seeds-v1",
        "parameter_set": param_name,
        "security_bits": params.security_bits,
        "n": params.n,
        "num_seeds": requested_count,
        "master_seed": requested_master,
        "purpose": (
            "Paired side-channel acquisition across compiler "
            "optimization levels"
        ),
        "seeds": [
            {
                "seed_id": index,
                "sk_seed_hex": seed.hex(),
                "sha256": hashlib.sha256(seed).hexdigest(),
            }
            for index, seed in enumerate(seeds)
        ],
    }

    with open(path, "w", encoding="utf-8") as file:
        json.dump(
            manifest,
            file,
            ensure_ascii=False,
            indent=2,
        )

    runtime_manifest = dict(manifest)
    runtime_manifest["stored_num_seeds"] = requested_count
    runtime_manifest["requested_num_seeds"] = requested_count
    runtime_manifest["selected_seed_ids"] = list(
        range(requested_count)
    )
    runtime_manifest["selection_mode"] = (
        "overwritten_pool"
        if bool(overwrite)
        else "created_new_pool"
    )

    return seeds, runtime_manifest


