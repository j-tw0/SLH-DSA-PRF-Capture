CAPTURE_BUILD_METADATA: Dict[str, Any] = {}


def set_capture_build_metadata(
    metadata: Optional[Dict[str, Any]] = None,
    **kwargs: Any,
) -> Dict[str, Any]:
    """Register firmware/build metadata for subsequently saved captures."""
    global CAPTURE_BUILD_METADATA
    merged: Dict[str, Any] = {}
    if metadata is not None:
        merged.update(dict(metadata))
    merged.update(kwargs)
    clean: Dict[str, Any] = {}
    for key, value in merged.items():
        if isinstance(value, os.PathLike):
            clean[str(key)] = str(value)
        elif isinstance(value, (str, int, float, bool)) or value is None:
            clean[str(key)] = value
        else:
            clean[str(key)] = str(value)
    CAPTURE_BUILD_METADATA = clean
    return dict(CAPTURE_BUILD_METADATA)


def get_capture_build_metadata() -> Dict[str, Any]:
    """Return a copy of the registered firmware/build metadata."""
    return dict(CAPTURE_BUILD_METADATA)

