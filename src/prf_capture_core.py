@dataclass(frozen=True)
class SLHParameterSet:
    name: str
    security_bits: int
    n: int
    full_height: int
    d: int
    fors_height: int
    fors_trees: int
    wots_w: int = 16
    wots_logw: int = 4

    @property
    def variant(self) -> str:
        return self.name[-1]

    @property
    def profile_name(self) -> str:
        return "fast" if self.variant == "f" else "small"

    @property
    def tree_height(self) -> int:
        return self.full_height // self.d

    @property
    def wots_len1(self) -> int:
        return (8 * self.n) // self.wots_logw

    @property
    def wots_len2(self) -> int:
        # floor(log_w(len1*(w-1))) + 1
        value = self.wots_len1 * (self.wots_w - 1)
        out = 0
        while value > 0:
            out += 1
            value //= self.wots_w
        return out

    @property
    def wots_len(self) -> int:
        return self.wots_len1 + self.wots_len2


