def windows_to_wsl_path(path: str | os.PathLike) -> str:
    """Convert C:/... or C:\\... to /mnt/c/... when running under WSL/Linux."""
    s = str(path)
    if os.name != "nt" and len(s) >= 3 and s[1] == ":" and s[2] in ("\\", "/"):
        drive = s[0].lower()
        rest = s[3:].replace("\\", "/")
        return f"/mnt/{drive}/{rest}"
    return s


def ensure_dir(path: str | os.PathLike) -> str:
    p = windows_to_wsl_path(path)
    os.makedirs(p, exist_ok=True)
    return p


def timestamp() -> str:
    return datetime.now().strftime("%y%m%d_%H%M%S")


def normalize_mode(mode: int | str) -> int:
    if mode in (MODE_SHA2, "sha2", "sha", "sha256"):
        return MODE_SHA2
    if mode in (MODE_SHAKE, "shake", "shake256"):
        return MODE_SHAKE
    raise ValueError("mode must be 0/'sha2' or 1/'shake'")


def mode_name(mode: int | str) -> str:
    return "sha2" if normalize_mode(mode) == MODE_SHA2 else "shake"

# ---------------------------------------------------------------------------
# Address utilities
# ---------------------------------------------------------------------------
def _require_len(name: str, data: bytes | bytearray, expected: int) -> None:
    if len(data) != expected:
        raise ValueError(f"{name} must be {expected} bytes, got {len(data)}")


def ull_to_bytes(outlen: int, x: int) -> bytes:
    b = bytearray(outlen)
    x = int(x)
    for i in range(outlen - 1, -1, -1):
        b[i] = x & 0xFF
        x >>= 8
    return bytes(b)


def u32_to_bytes(x: int) -> bytes:
    return int(x & 0xFFFFFFFF).to_bytes(4, "big")


def addr_new() -> bytearray:
    return bytearray(ADRS_FULL_BYTES)


def _offsets(mode: int | str) -> Dict[str, int]:
    if normalize_mode(mode) == MODE_SHA2:
        return {
            "layer": SHA2_OFFSET_LAYER,
            "tree": SHA2_OFFSET_TREE,
            "type": SHA2_OFFSET_TYPE,
            "kp": SHA2_OFFSET_KP_ADDR,
            "chain": SHA2_OFFSET_CHAIN_ADDR,
            "hash": SHA2_OFFSET_HASH_ADDR,
            "tree_hgt": SHA2_OFFSET_TREE_HGT,
            "tree_index": SHA2_OFFSET_TREE_INDEX,
        }
    return {
        "layer": SHAKE_OFFSET_LAYER,
        "tree": SHAKE_OFFSET_TREE,
        "type": SHAKE_OFFSET_TYPE,
        "kp": SHAKE_OFFSET_KP_ADDR,
        "chain": SHAKE_OFFSET_CHAIN_ADDR,
        "hash": SHAKE_OFFSET_HASH_ADDR,
        "tree_hgt": SHAKE_OFFSET_TREE_HGT,
        "tree_index": SHAKE_OFFSET_TREE_INDEX,
    }


def set_layer_addr(addr: bytearray, layer: int, mode: int | str = "sha2") -> None:
    addr[_offsets(mode)["layer"]] = int(layer) & 0xFF


def set_tree_addr(addr: bytearray, tree: int, mode: int | str = "sha2") -> None:
    off = _offsets(mode)["tree"]
    addr[off:off + 8] = ull_to_bytes(8, int(tree))


def set_type(addr: bytearray, typ: int, mode: int | str = "sha2") -> None:
    addr[_offsets(mode)["type"]] = int(typ) & 0xFF


def set_keypair_addr(addr: bytearray, keypair: int, mode: int | str = "sha2") -> None:
    off = _offsets(mode)["kp"]
    addr[off:off + 4] = u32_to_bytes(int(keypair))


def set_chain_addr(addr: bytearray, chain: int, mode: int | str = "sha2") -> None:
    addr[_offsets(mode)["chain"]] = int(chain) & 0xFF


def set_hash_addr(addr: bytearray, h: int, mode: int | str = "sha2") -> None:
    addr[_offsets(mode)["hash"]] = int(h) & 0xFF


def set_tree_height(addr: bytearray, h: int, mode: int | str = "sha2") -> None:
    addr[_offsets(mode)["tree_hgt"]] = int(h) & 0xFF


def set_tree_index(addr: bytearray, idx: int, mode: int | str = "sha2") -> None:
    off = _offsets(mode)["tree_index"]
    addr[off:off + 4] = u32_to_bytes(int(idx))


def compress_adrs_for_sha2(addr32: bytes | bytearray | np.ndarray) -> bytes:
    if isinstance(addr32, (bytes, bytearray)):
        b = bytes(addr32)
    else:
        b = bytes(np.asarray(addr32, dtype=np.uint8).tolist())
    _require_len("addr32", b, ADRS_FULL_BYTES)
    return b[:ADRS_COMPRESSED_BYTES]


def build_wots_prf_addr(layer: int, tree: int, keypair: int, chain: int, hash_: int = 0, mode: int | str = "sha2") -> bytes:
    addr = addr_new()
    set_layer_addr(addr, layer, mode)
    set_tree_addr(addr, tree, mode)
    set_type(addr, SLH_ADDR_TYPE_WOTSPRF, mode)
    set_keypair_addr(addr, keypair, mode)
    set_chain_addr(addr, chain, mode)
    set_hash_addr(addr, hash_, mode)
    return bytes(addr)


def build_fors_prf_addr(layer: int, tree: int, keypair: int, tree_height: int, tree_index: int, mode: int | str = "sha2") -> bytes:
    addr = addr_new()
    set_layer_addr(addr, layer, mode)
    set_tree_addr(addr, tree, mode)
    set_type(addr, SLH_ADDR_TYPE_FORSPRF, mode)
    set_keypair_addr(addr, keypair, mode)
    set_tree_height(addr, tree_height, mode)
    set_tree_index(addr, tree_index, mode)
    return bytes(addr)


def max_tree_bits_for_layer(layer: int) -> int:
    if not 0 <= int(layer) < SLH_D:
        raise ValueError(f"layer must be in 0..{SLH_D - 1}, got {layer}")
    bits = SLH_FULL_HEIGHT - SLH_TREE_HEIGHT * (int(layer) + 1)
    return max(bits, 0)


def max_tree_for_layer(layer: int) -> int:
    bits = max_tree_bits_for_layer(layer)
    return (1 << bits) - 1 if bits > 0 else 0


def random_tree_for_layer(layer: int, rng: Optional[random.Random] = None) -> int:
    r = rng or random
    return r.randint(0, max_tree_for_layer(layer))


def parameter_address_ranges(
    name: Optional[str | int] = None,
) -> Dict[str, Any]:
    """Return valid host-generated address ranges for one parameter set."""
    params = PARAMS if name is None else get_parameter_set(name)
    h_prime = params.tree_height

    return {
        "parameter_set": params.name,
        "profile": params.profile_name,
        "layer": (0, params.d - 1),
        "keypair": (0, (1 << h_prime) - 1),
        "wots_chain": (0, params.wots_len - 1),
        "wots_hash_default": 0,
        "tree_bits_layer0": params.full_height - h_prime,
        "tree_layer0": (
            0,
            (1 << (params.full_height - h_prime)) - 1,
        ),
        "fors_tree_height": 0,
        "fors_tree_index": (
            0,
            params.fors_trees * (1 << params.fors_height) - 1,
        ),
    }

# ---------------------------------------------------------------------------
# Python reference matching slh_dsa_prf_target.c
# ---------------------------------------------------------------------------
def reference_digest(mode: int | str, pk_seed: bytes, sk_seed: bytes, addr32: bytes) -> bytes:
    _require_len("pk_seed", pk_seed, SLH_N)
    _require_len("sk_seed", sk_seed, SLH_N)
    _require_len("addr32", addr32, ADRS_FULL_BYTES)

    mode_i = normalize_mode(mode)
    if mode_i == MODE_SHA2:
        addr_c = compress_adrs_for_sha2(addr32)
        msg = pk_seed + bytes(SHA2_ZPAD_LEN) + addr_c + sk_seed
        return hashlib.sha256(msg).digest()[:OUT_LEN]
    return hashlib.shake_256(pk_seed + bytes(addr32) + sk_seed).digest(OUT_LEN)

def _resolve_seeds(
    pk_seed: Optional[bytes],
    sk_seed: Optional[bytes],
    sk_prf: Optional[bytes],
) -> Tuple[bytes, bytes, Optional[bytes]]:
    pk = PUB_SEED if pk_seed is None else bytes(pk_seed)
    sk = SK_SEED if sk_seed is None else bytes(sk_seed)
    prf = SK_PRF if sk_prf is None else bytes(sk_prf)
    _require_len("pk_seed", pk, SLH_N)
    _require_len("sk_seed", sk, SLH_N)
    if prf is not None:
        _require_len("sk_prf", prf, SLH_N)
    return pk, sk, prf


# ---------------------------------------------------------------------------
# SimpleSerial-safe wrappers
# ---------------------------------------------------------------------------
def _flush_target(target) -> None:
    try:
        target.flush()
    except Exception:
        pass


def _wait_ack_checked(target, timeout: int, label: str):
    ack = target.simpleserial_wait_ack(timeout)
    if ack is None:
        raise TimeoutError(f"{label} ACK timeout")
    return ack


def read_mode(target, timeout: int = 250) -> int:
    """Read current hash mode.

    For this target, read commands (B/R/Z) return an ``r`` response.  Depending
    on the ChipWhisperer SimpleSerial host/firmware combination, an explicit
    z00 ACK for these read commands may be absent or already consumed by
    simpleserial_read().  Therefore we do NOT require an additional ACK here.
    """
    _flush_target(target)
    target.simpleserial_write("B", b"")
    data = target.simpleserial_read("r", 1, timeout=timeout)
    if data is None or len(data) != 1:
        raise TimeoutError("B/read mode timeout")
    return int(data[0])


def read_target_n(target, timeout: int = 250) -> int:
    """Read the firmware's compile-time n value (16, 24, or 32)."""
    _flush_target(target)
    target.simpleserial_write("N", b"")
    data = target.simpleserial_read("r", 1, timeout=timeout)
    if data is None or len(data) != 1:
        raise TimeoutError("N/read target n timeout")
    return int(data[0])


def read_addr(target, timeout: int = 250) -> bytes:
    """Read current 32-byte ADRS without requiring a trailing read ACK."""
    _flush_target(target)
    target.simpleserial_write("R", b"")
    data = target.simpleserial_read("r", ADRS_FULL_BYTES, timeout=timeout)
    if data is None or len(data) != ADRS_FULL_BYTES:
        raise TimeoutError("R/read ADRS timeout")
    return bytes(data)


def set_mode(target, mode: int | str, timeout: int = 250, verify: bool = True) -> int:
    mode_i = normalize_mode(mode)
    _flush_target(target)
    target.simpleserial_write("M", bytearray([mode_i]))
    _wait_ack_checked(target, timeout, "M/set mode")
    if verify:
        rb = read_mode(target, timeout=timeout)
        if rb != mode_i:
            raise RuntimeError(f"mode readback mismatch: got {rb}, expected {mode_i}")
    return mode_i


def send_pk_seed(target, pk_seed: bytes, timeout: int = 250) -> None:
    _require_len("pk_seed", pk_seed, SLH_N)
    _flush_target(target)
    target.simpleserial_write("P", pk_seed)
    _wait_ack_checked(target, timeout, "P/set PK.seed")


def send_sk_seed(target, sk_seed: bytes, timeout: int = 250) -> None:
    _require_len("sk_seed", sk_seed, SLH_N)
    _flush_target(target)
    target.simpleserial_write("S", sk_seed)
    _wait_ack_checked(target, timeout, "S/set SK.seed")


def send_sk_prf(target, sk_prf: bytes, timeout: int = 250) -> None:
    _require_len("sk_prf", sk_prf, SLH_N)
    _flush_target(target)
    target.simpleserial_write("Q", sk_prf)
    _wait_ack_checked(target, timeout, "Q/set SK.prf")


def send_addr(target, addr32: bytes, timeout: int = 250, verify: bool = False) -> None:
    _require_len("addr32", addr32, ADRS_FULL_BYTES)
    _flush_target(target)
    target.simpleserial_write("A", addr32)
    _wait_ack_checked(target, timeout, "A/set ADRS")
    if verify:
        rb = read_addr(target, timeout=timeout)
        if rb != bytes(addr32):
            raise RuntimeError("ADRS readback mismatch")


def configure_static(
    target,
    *,
    mode: int | str,
    pk_seed: Optional[bytes] = None,
    sk_seed: Optional[bytes] = None,
    sk_prf: Optional[bytes] = None,
    timeout: int = 250,
    verify_target_n: bool = True,
) -> None:
    pk_seed = PUB_SEED if pk_seed is None else bytes(pk_seed)
    sk_seed = SK_SEED if sk_seed is None else bytes(sk_seed)
    sk_prf = SK_PRF if sk_prf is None else bytes(sk_prf)
    if verify_target_n:
        target_n = read_target_n(target, timeout=timeout)
        if target_n != SLH_N:
            raise RuntimeError(
                f"firmware/helper parameter mismatch: target n={target_n}, "
                f"helper {ACTIVE_PARAM_SET} n={SLH_N}. Rebuild and reprogram the target."
            )
    set_mode(target, mode, timeout=timeout, verify=True)
    send_pk_seed(target, pk_seed, timeout=timeout)
    send_sk_seed(target, sk_seed, timeout=timeout)
    if sk_prf is not None:
        send_sk_prf(target, sk_prf, timeout=timeout)
    _flush_target(target)


def reset_target(scope, target=None, sleep_low: float = 0.05, sleep_after: float = 0.30) -> None:
    if target is not None:
        _flush_target(target)
    try:
        scope.io.nrst = "low"
        time.sleep(float(sleep_low))
        scope.io.nrst = "high_z"
        time.sleep(float(sleep_after))
    finally:
        if target is not None:
            _flush_target(target)


def reset_and_configure(
    scope,
    target,
    *,
    mode: int | str,
    pk_seed: Optional[bytes] = None,
    sk_seed: Optional[bytes] = None,
    sk_prf: Optional[bytes] = None,
    timeout: int = 250,
) -> None:
    pk_seed, sk_seed, sk_prf = _resolve_seeds(pk_seed, sk_seed, sk_prf)
    reset_target(scope, target)
    configure_static(target, mode=mode, pk_seed=pk_seed, sk_seed=sk_seed, sk_prf=sk_prf, timeout=timeout)


def capture_trace(scope, target, timeout: int = 250) -> Tuple[bytes, np.ndarray]:
    """Execute target command T once, then read Z output safely."""
    _flush_target(target)
    scope.arm()
    target.simpleserial_write("T", b"")
    ret = scope.capture()
    _wait_ack_checked(target, timeout, "T/run")
    if ret:
        raise TimeoutError("scope capture timeout")

    target.simpleserial_write("Z", b"")
    out = target.simpleserial_read("r", OUT_LEN, timeout=timeout)
    if out is None or len(out) != OUT_LEN:
        raise TimeoutError("Z/read output timeout")
    # Do not require a trailing ACK for Z/read output. Some SimpleSerial stacks
    # do not send one for read commands, and simpleserial_read() may consume it.
    wave = scope.get_last_trace(as_int=False)
    return bytes(out), wave

# ---------------------------------------------------------------------------
# Case builders
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class Case:
    kind: int
    layer: int
    tree: int
    keypair: int
    chain: int
    hash: int
    tree_height: int
    tree_index: int
    addr: bytes

    def meta_row(self, is_fixed: int, mode: int) -> List[int]:
        return [
            int(is_fixed), int(mode), int(self.kind), int(self.layer), int(self.tree), int(self.keypair),
            int(self.chain), int(self.hash), int(self.tree_height), int(self.tree_index),
        ]


def make_wots_case(*, fixed: bool = False, rng: Optional[random.Random] = None, mode: int | str = "sha2", hash_: int = 0) -> Case:
    r = rng or random
    if fixed:
        layer, tree, keypair, chain = 0, 0, 0, 0
    else:
        layer = r.randint(0, SLH_D - 1)
        tree = random_tree_for_layer(layer, r)
        keypair = r.randint(0, (1 << SLH_TREE_HEIGHT) - 1)
        chain = r.randint(0, SLH_WOTS_LEN - 1)
    addr = build_wots_prf_addr(layer, tree, keypair, chain, hash_=hash_, mode=mode)
    return Case(KIND_WOTS, layer, tree, keypair, chain, hash_, 0, 0, addr)


def make_fors_case(*, fixed: bool = False, rng: Optional[random.Random] = None, mode: int | str = "sha2") -> Case:
    r = rng or random
    layer = 0
    if fixed:
        tree, keypair, tree_index = 0, 0, 0
    else:
        tree = random_tree_for_layer(0, r)
        keypair = r.randint(0, (1 << SLH_TREE_HEIGHT) - 1)
        tree_index = r.randint(0, SLH_FORS_TREES * (1 << SLH_FORS_HEIGHT) - 1)
    tree_height = 0
    addr = build_fors_prf_addr(layer, tree, keypair, tree_height, tree_index, mode=mode)
    return Case(KIND_FORS, layer, tree, keypair, 0, 0, tree_height, tree_index, addr)


def make_case_for_kind(kind: str, fixed: bool, rng_obj: Optional[random.Random] = None, mode: int | str = "sha2") -> Case:
    kind_l = str(kind).lower()
    if kind_l == "wots":
        return make_wots_case(fixed=bool(fixed), rng=rng_obj, mode=mode)
    if kind_l == "fors":
        return make_fors_case(fixed=bool(fixed), rng=rng_obj, mode=mode)
    raise ValueError("kind must be 'wots' or 'fors'")


def make_calibration_case(kind: str = "wots", mode: int | str = "sha2") -> Case:
    return make_case_for_kind(kind, fixed=True, rng_obj=random.Random(0), mode=mode)

