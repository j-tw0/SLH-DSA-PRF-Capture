def hex_to_bytes(s: str) -> bytes:
    return bytes.fromhex(str(s).replace(" ", ""))


def normalize_security_level(level: str | int) -> int:
    value = str(level).strip().lower()
    value = value.replace("slh-dsa-", "").replace("sha2-", "").replace("shake-", "")
    value = value.replace("_", "").replace("-", "")
    if value.endswith(("f", "s")):
        value = value[:-1]
    if value not in ("128", "192", "256"):
        raise ValueError("security level must be 128, 192, or 256")
    return int(value)


def normalize_variant(variant: str) -> str:
    value = str(variant).strip().lower()
    aliases = {
        "f": "f",
        "fast": "f",
        "s": "s",
        "small": "s",
        "slow": "s",
    }
    if value not in aliases:
        raise ValueError("variant must be 'f'/'fast' or 's'/'small'")
    return aliases[value]


def compose_parameter_set(
    security_level: str | int,
    variant: str,
) -> str:
    return f"{normalize_security_level(security_level)}{normalize_variant(variant)}"


def normalize_param_set(name: str | int) -> str:
    value = str(name).strip().lower()
    value = value.replace("slh-dsa-", "").replace("sha2-", "").replace("shake-", "")
    value = value.replace("_", "").replace("-", "")

    aliases = {
        "128": "128f",
        "128f": "128f",
        "128fast": "128f",
        "128s": "128s",
        "128small": "128s",
        "192": "192f",
        "192f": "192f",
        "192fast": "192f",
        "192s": "192s",
        "192small": "192s",
        "256": "256f",
        "256f": "256f",
        "256fast": "256f",
        "256s": "256s",
        "256small": "256s",
    }
    if value not in aliases:
        raise ValueError(
            "parameter set must be one of "
            "'128f', '128s', '192f', '192s', '256f', or '256s'"
        )
    return aliases[value]


def get_parameter_set(name: str | int) -> SLHParameterSet:
    return PARAMETER_SETS[normalize_param_set(name)]


def get_default_seeds(name: str | int) -> Dict[str, bytes]:
    key = normalize_param_set(name)
    return {k: hex_to_bytes(v) for k, v in DEFAULT_SEEDS_HEX[key].items()}


def select_parameter_set(name: str | int = "128f") -> SLHParameterSet:
    """Select the active parameter set used by address and capture helpers."""
    global ACTIVE_PARAM_SET, PARAMS
    global SLH_N, OUT_LEN, SHA2_ZPAD_LEN
    global SLH_FULL_HEIGHT, SLH_D, SLH_TREE_HEIGHT
    global SLH_FORS_HEIGHT, SLH_FORS_TREES
    global SLH_WOTS_W, SLH_WOTS_LOGW, SLH_WOTS_LEN1, SLH_WOTS_LEN2, SLH_WOTS_LEN
    global SK_SEED, SK_PRF, PUB_SEED, ROOT

    ACTIVE_PARAM_SET = normalize_param_set(name)
    PARAMS = PARAMETER_SETS[ACTIVE_PARAM_SET]
    SLH_N = PARAMS.n
    OUT_LEN = PARAMS.n
    SHA2_ZPAD_LEN = 64 - PARAMS.n
    SLH_FULL_HEIGHT = PARAMS.full_height
    SLH_D = PARAMS.d
    SLH_TREE_HEIGHT = PARAMS.tree_height
    SLH_FORS_HEIGHT = PARAMS.fors_height
    SLH_FORS_TREES = PARAMS.fors_trees
    SLH_WOTS_W = PARAMS.wots_w
    SLH_WOTS_LOGW = PARAMS.wots_logw
    SLH_WOTS_LEN1 = PARAMS.wots_len1
    SLH_WOTS_LEN2 = PARAMS.wots_len2
    SLH_WOTS_LEN = PARAMS.wots_len

    seeds = get_default_seeds(ACTIVE_PARAM_SET)
    SK_SEED = seeds["sk_seed"]
    SK_PRF = seeds["sk_prf"]
    PUB_SEED = seeds["pk_seed"]
    ROOT = seeds["root"]
    return PARAMS


