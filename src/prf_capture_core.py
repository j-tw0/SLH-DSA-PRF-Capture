# Fixed/random WOTS and FORS capture
# ---------------------------------------------------------------------------
def capture_fixed_random_streaming(
    scope,
    target,
    prefix: str,
    *,
    kind: str,
    n_fixed: int,
    n_random: int,
    mode: int | str = "sha2",
    pk_seed: Optional[bytes] = None,
    sk_seed: Optional[bytes] = None,
    sk_prf: Optional[bytes] = None,
    timeout: int = 250,
    rng_seed: int = 1234,
    shuffle_sequence: bool = True,
    verify_addr_each_time: bool = False,
    verify_result: bool = True,
    verify_first_n: int = 5,
    flush_every: int = 1000,
) -> str:
    """Capture WOTS or FORS traces; verify only the first ``verify_first_n`` outputs."""
    prefix = windows_to_wsl_path(prefix)
    os.makedirs(os.path.dirname(prefix) or ".", exist_ok=True)
    mode_i = normalize_mode(mode)
    mode_l = mode_name(mode_i)
    pk_seed, sk_seed, sk_prf = _resolve_seeds(pk_seed, sk_seed, sk_prf)
    kind_l = str(kind).lower()
    if kind_l not in ("wots", "fors"):
        raise ValueError("kind must be 'wots' or 'fors'")

    configure_static(target, mode=mode_i, pk_seed=pk_seed, sk_seed=sk_seed, sk_prf=sk_prf, timeout=timeout)

    num_fixed = int(n_fixed)
    num_random = int(n_random)
    if num_fixed < 0 or num_random < 0:
        raise ValueError("n_fixed and n_random must be non-negative")
    if num_fixed + num_random <= 0:
        raise ValueError("at least one of n_fixed or n_random must be positive")

    sequence = [True] * num_fixed + [False] * num_random
    if shuffle_sequence:
        random.Random(int(rng_seed)).shuffle(sequence)
    case_rng = random.Random(int(rng_seed))

    # Persist the exact acquisition order.  The split trace arrays below are
    # stored separately as fixed/random, but this file preserves the original
    # interleaved order used during measurement.
    acquisition_is_fixed = np.asarray(
        [1 if value else 0 for value in sequence],
        dtype=np.uint8,
    )
    np.save(
        prefix + "_acquisition_is_fixed.npy",
        acquisition_is_fixed,
    )

    fixed_row = 0
    random_row = 0
    acquisition_map = np.empty(
        (len(sequence), 2),
        dtype=np.uint64,
    )
    for acquisition_index, value in enumerate(sequence):
        if bool(value):
            acquisition_map[acquisition_index, :] = (
                1,
                fixed_row,
            )
            fixed_row += 1
        else:
            acquisition_map[acquisition_index, :] = (
                0,
                random_row,
            )
            random_row += 1
    np.save(
        prefix + "_acquisition_map.npy",
        acquisition_map,
    )
    np.save(
        prefix + "_acquisition_map_columns.npy",
        np.asarray(
            ["is_fixed", "split_row"],
            dtype=object,
        ),
    )

    print("mode    :", mode_l)
    print("kind    :", kind_l)
    print("n_fixed :", num_fixed)
    print("n_random:", num_random)
    print("total   :", len(sequence))
    print("shuffle :", bool(shuffle_sequence))
    print("scope.adc.samples:", int(scope.adc.samples))
    print("verify outputs:", "all" if int(verify_first_n) < 0 else f"first {int(verify_first_n)}")

    _save_meta_columns(prefix)
    _, fixed_addrs_mm, fixed_params_mm = _init_split_arrays(prefix, "fixed", num_fixed)
    _, random_addrs_mm, random_params_mm = _init_split_arrays(prefix, "random", num_random)
    fixed_mm = None
    random_mm = None
    trace_len = None
    fi = 0
    ri = 0

    for is_fixed in tqdm(sequence, desc=f"{mode_l}/{kind_l}"):
        case = make_case_for_kind(kind_l, bool(is_fixed), case_rng, mode=mode_i)
        send_addr(target, case.addr, timeout=timeout, verify=verify_addr_each_time)
        result, wave = capture_trace(scope, target, timeout=timeout)
        capture_index = fi + ri
        if verify_result and (int(verify_first_n) < 0 or capture_index < int(verify_first_n)):
            _verify_digest_or_raise(mode_i, pk_seed, sk_seed, case, result, index=capture_index)
        wave = np.asarray(wave, dtype=np.float32)

        if trace_len is None:
            trace_len = _trace_len_from_wave(scope, wave)
            print("captured_len:", int(wave.shape[0]))
            print("requested_len(scope.adc.samples):", int(scope.adc.samples))
            print("save trace_len:", int(trace_len))
            if num_fixed > 0:
                fixed_mm = open_memmap(
                    prefix + "_traces_fixed.npy",
                    mode="w+",
                    dtype=np.float32,
                    shape=(num_fixed, trace_len),
                )
            if num_random > 0:
                random_mm = open_memmap(
                    prefix + "_traces_random.npy",
                    mode="w+",
                    dtype=np.float32,
                    shape=(num_random, trace_len),
                )

        if wave.shape[0] < trace_len:
            raise RuntimeError(f"trace too short: got {wave.shape[0]}, expected at least {trace_len}")
        wave = wave[:trace_len]

        if bool(is_fixed):
            fixed_mm[fi, :] = wave
            fixed_addrs_mm[fi, :] = np.frombuffer(case.addr, dtype=np.uint8)
            fixed_params_mm[fi, :] = np.asarray(case.meta_row(is_fixed=1, mode=mode_i), dtype=np.uint64)
            fi += 1
        else:
            random_mm[ri, :] = wave
            random_addrs_mm[ri, :] = np.frombuffer(case.addr, dtype=np.uint8)
            random_params_mm[ri, :] = np.asarray(case.meta_row(is_fixed=0, mode=mode_i), dtype=np.uint64)
            ri += 1

        if (fi + ri) % int(flush_every) == 0:
            _flush_many(fixed_mm, random_mm, fixed_addrs_mm, random_addrs_mm, fixed_params_mm, random_params_mm)

    _flush_many(fixed_mm, random_mm, fixed_addrs_mm, random_addrs_mm, fixed_params_mm, random_params_mm)
    print("saved prefix:", prefix)
    print("captured fixed :", fi)
    print("captured random:", ri)
    return prefix


