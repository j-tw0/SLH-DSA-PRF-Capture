"""
Streaming capture helper for SLH-DSA PRF experiments on ChipWhisperer.

Supported parameter sets:
    SLH-DSA-{SHA2,SHAKE}-128f / 128s  (n=16)
    SLH-DSA-{SHA2,SHAKE}-192f / 192s  (n=24)
    SLH-DSA-{SHA2,SHAKE}-256f / 256s  (n=32)

The host selects both the security level and the f/s profile.  The security
level controls the SimpleSerial seed/output length and therefore must match the
firmware build.  The f/s profile controls the valid address ranges generated by
the host: h, d, h', FORS height a, and FORS tree count k.

Read commands B/R/Z/N return only an ``r`` response; no trailing ACK is required.
Large captures are streamed directly to .npy memmaps.

The exact-count random capture API stores exactly the user-requested number of
WOTS, FORS, mixed, or signature-like PRF traces.

SHA2 PRF:
    Trunc_n(SHA-256(PK.seed || zero[64-n] || ADRS^c || SK.seed))
SHAKE PRF:
    SHAKE256(PK.seed || ADRS || SK.seed, n)
"""
